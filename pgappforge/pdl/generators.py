	def generate_schema_files(self, schema: PDLSchema) -> dict[str, str]:
		"""Generate schema-level files (one per project, not per entity)."""
		return {
			"Dockerfile":                    self.generate_dockerfile(schema),
			"docker-compose.yml":            self.generate_docker_compose(schema),
			".github/workflows/ci.yml":      self.generate_github_actions(schema),
		}

	# ------------------------------------------------------------------
	# File I/O helper
	# ------------------------------------------------------------------

	def _write(self, base: Path, entity: PDLEntity, artifact: str, code: str) -> Path:
		"""Write *code* to the appropriate path under *base*."""
		ts       = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
		filename = {
			"models.py":    "models.py",
			"migration.py": f"migrations/{ts}_{entity.table}.py",
			"views.py":     "views.py",
			"api.py":       "api.py",
			"test_model.py": f"tests/test_{_snake(entity.name)}.py",
		}.get(artifact, artifact)

		path = base / filename
		path.parent.mkdir(parents=True, exist_ok=True)
		path.write_text(code, encoding="utf-8")
		return path


