"""
pgappforge/plugins/erp/platform/ml_predictions/views.py

Flask-AppBuilder views for the ML Predictions plugin.

MLPredictionView         — read-only list of persisted predictions.
MLPredictionsDashboardView — live counts by prediction_type and label.
"""
from __future__ import annotations

import logging

import sqlalchemy as sa
from flask import render_template, jsonify, request
from pgappforge.baseviews import expose
from pgappforge.models.sqla.interface import SQLAInterface
from pgappforge.security.decorators import has_access

from pgappforge.plugins.erp.base_view import BaseERPModelView, BaseERPView
from pgappforge.plugins.erp.platform.ml_predictions.models import MLPrediction

log = logging.getLogger(__name__)


class MLPredictionView(BaseERPModelView):
	"""Read-only list of persisted ML prediction results."""

	datamodel = SQLAInterface(MLPrediction)

	list_title = "ML Predictions"
	list_columns = [
		"prediction_type",
		"reference_type",
		"reference_id",
		"label",
		"score",
		"model_version",
		"created_at",
	]
	search_columns = ["prediction_type", "reference_type", "reference_id", "label"]
	order_columns  = ["created_at", "prediction_type", "score"]

	# Predictions are generated by the engine — no manual add/edit
	base_permissions = ["can_list", "can_show"]


class MLPredictionsDashboardView(BaseERPView):
	"""ML Predictions dashboard — live counts by type and label."""

	route_base = "/platform/ml"

	@expose("/")
	@has_access
	def index(self):
		sess = self._session()

		total = self._count(MLPrediction, session=sess)

		# Counts per prediction_type
		type_counts: list[dict] = []
		label_counts: list[dict] = []
		try:
			rows = sess.execute(
				sa.select(
					MLPrediction.prediction_type,
					sa.func.count().label("n"),
				).group_by(MLPrediction.prediction_type)
			).all()
			type_counts = [{"label": r.prediction_type, "value": r.n} for r in rows]

			rows2 = sess.execute(
				sa.select(
					MLPrediction.label,
					sa.func.count().label("n"),
				).where(MLPrediction.label.isnot(None))
				.group_by(MLPrediction.label)
			).all()
			label_counts = [{"label": r.label, "value": r.n} for r in rows2]
		except Exception:
			pass

		# Shortcut counts for common high-signal labels
		duplicates = self._count(MLPrediction, session=sess, label="DUPLICATE")
		anomalies  = self._count(MLPrediction, session=sess, label="ANOMALY")
		high_risk  = self._count(MLPrediction, session=sess, label="HIGH")

		kpi_html = self.kpi_cards([
			{
				"label":  "Total Predictions",
				"value":  total,
				"icon":   "fa-brain",
				"color":  "#1a56db",
			},
			{
				"label":  "Duplicate Invoices",
				"value":  duplicates,
				"icon":   "fa-copy",
				"color":  "#e3a008",
			},
			{
				"label":  "GL Anomalies",
				"value":  anomalies,
				"icon":   "fa-exclamation-triangle",
				"color":  "#e02424",
			},
			{
				"label":  "High Attrition Risk",
				"value":  high_risk,
				"icon":   "fa-user-times",
				"color":  "#ff5a1f",
			},
		])

		type_chart_html = self.chart(
			rows=type_counts,
			chart_type="doughnut",
			x_col="label",
			y_col="value",
			title="Predictions by Type",
		) if type_counts else ""

		label_chart_html = self.chart(
			rows=label_counts,
			chart_type="bar",
			x_col="label",
			y_col="value",
			title="Predictions by Label",
		) if label_counts else ""

		return render_template(
			"platform/ml_dashboard.html",
			kpi_html=kpi_html,
			type_chart_html=type_chart_html,
			label_chart_html=label_chart_html,
			appbuilder=self.appbuilder,
		)

	# ------------------------------------------------------------------
	# API endpoints for on-demand predictions
	# ------------------------------------------------------------------

	@expose("/api/duplicate", methods=["POST"])
	@has_access
	def api_duplicate(self):
		"""Detect AP invoice duplicate on demand.

		JSON body: {invoice_id, tenant_id, similarity_threshold?}
		"""
		from pgappforge.plugins.erp.platform.ml_predictions.services import MLPredictionService
		body      = request.get_json(force=True) or {}
		invoice_id = body.get("invoice_id")
		tenant_id  = body.get("tenant_id", self._tenant_id())
		if not invoice_id:
			return jsonify({"error": "invoice_id is required"}), 400
		threshold = float(body.get("similarity_threshold", 0.85))
		sess   = self._session()
		result = MLPredictionService().detect_duplicate_invoice(
			invoice_id, tenant_id, sess, similarity_threshold=threshold
		)
		return jsonify(result)

