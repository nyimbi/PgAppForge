"""
Built-in ReportForge business report templates.

Each template describes how to pre-configure a new Report with
bands, fields, branding defaults, and sample SQL.

Available templates
-------------------
invoice          — Sales invoice with line items, tax, total
quote            — Customer quotation / price list
statement        — Statement of account (balance, transactions)
business_letter  — Formal business letter (mail merge from a query)
tabular          — Generic data table (simplest starting point)
summary          — Executive summary with totals/KPIs per group
"""

from __future__ import annotations
from typing import Any


def _band(band_type, height_mm, bg="#ffffff", fields=None):
    return {"band_type": band_type, "height_mm": height_mm,
            "background_color": bg, "fields": fields or []}


def _field(ftype, x, y, w, h, text="", binding="", fmt="",
           bold=False, size=10, align="left",
           color="#000000", bg="transparent"):
    style = {"font_size": size, "bold": bold, "align": align,
              "color": color, "bg_color": bg}
    if text:
        style["text"] = text
    return {"field_type": ftype, "x_mm": x, "y_mm": y,
            "width_mm": w, "height_mm": h,
            "data_binding": binding or None,
            "format_string": fmt or None, "style": style}


