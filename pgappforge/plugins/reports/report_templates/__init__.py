def get_template(key):
    """Return the template dict for the given key, or None."""
    return TEMPLATES.get(key)


def list_templates():
    """Return list of template metadata dicts."""
    return [
        {"key": k, "label": t["label"], "description": t["description"], "icon": t.get("icon", "fa-file")}
        for k, t in TEMPLATES.items()
    ]
