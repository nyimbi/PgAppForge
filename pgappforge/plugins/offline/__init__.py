def create_plugin(appbuilder, config: dict[str, Any] | None = None) -> OfflinePlugin:
	"""
	Construct and return an OfflinePlugin bound to *appbuilder*.

	Does **not** call ``activate()`` — the caller controls the lifecycle::

	    plugin = create_plugin(appbuilder, config={
	        "PGAPPFORGE_OFFLINE_ENABLED": True,
	        "PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY": "client_wins",
	    })
	    plugin.activate()

	Args:
	    appbuilder: PgAppForge / AppBuilder instance.
	    config:     Optional config dict merged over built-in defaults.

	Returns:
	    An uninitialised OfflinePlugin ready for ``activate()``.
	"""
	return OfflinePlugin(appbuilder, config=config or {})


