# Cache version is intentionally a constant string so the SW can be
# invalidated by a deploy bump. Apps may override this via app config.
_SW_TEMPLATE = """\
/* PgAppForge Offline Service Worker — generated by pgappforge.plugins.offline */
/* Cache TTL hint: {{ cache_ttl }} seconds */

const CACHE_VERSION  = '{{ cache_version }}';
const STATIC_CACHE   = `pgaf-static-${{CACHE_VERSION}}`;
const API_CACHE      = `pgaf-api-${{CACHE_VERSION}}`;
const PAGE_CACHE     = `pgaf-pages-${{CACHE_VERSION}}`;
const CACHE_TTL_MS   = {{ cache_ttl }} * 1000;

/* Asset URL patterns to precache on install */
const STATIC_PATTERNS = [
  /\\/static\\/.*(\\.(css|js|woff2?|ttf|eot|svg|png|jpg|ico))$/i,
];
const API_PATTERNS    = [/^\\/api\\//i, /\\.json$/i];

/* ── Install: open caches (no aggressive precaching — runtime only) ── */
self.addEventListener('install', event => {{
  event.waitUntil(
    caches.open(STATIC_CACHE).then(() => self.skipWaiting())
  );
}});

/* ── Activate: prune old cache versions ── */
self.addEventListener('activate', event => {{
  event.waitUntil(
    caches.keys().then(keys =>
      Promise.all(
        keys
          .filter(k => k.startsWith('pgaf-') && ![STATIC_CACHE, API_CACHE, PAGE_CACHE].includes(k))
          .map(k => caches.delete(k))
      )
    ).then(() => self.clients.claim())
  );
}});

/* ── Fetch: strategy dispatch ── */
self.addEventListener('fetch', event => {{
  const {{ request }} = event;
  if (request.method !== 'GET') return;          /* only cache GETs       */
  const url = new URL(request.url);

  if (STATIC_PATTERNS.some(re => re.test(url.pathname))) {{
    event.respondWith(cacheFirst(request, STATIC_CACHE));
    return;
  }}

  if (API_PATTERNS.some(re => re.test(url.pathname))) {{
    event.respondWith(staleWhileRevalidate(request, API_CACHE));
    return;
  }}

  /* HTML pages: network-first, fall back to cache */
  if (request.headers.get('Accept')?.includes('text/html')) {{
    event.respondWith(networkFirst(request, PAGE_CACHE));
    return;
  }}
}});

/* ── Cache strategies ── */

async function cacheFirst(request, cacheName) {{
  const cache    = await caches.open(cacheName);
  const cached   = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}}

async function staleWhileRevalidate(request, cacheName) {{
  const cache    = await caches.open(cacheName);
  const cached   = await cache.match(request);
  const fetchPr  = fetch(request).then(response => {{
    if (response.ok) {{
      const copy = response.clone();
      copy.headers?.get;                          /* keep reference alive  */
      cache.put(request, response.clone());
    }}
    return response;
  }}).catch(() => cached);                        /* network fail → stale  */
  return cached || fetchPr;
}}

async function networkFirst(request, cacheName) {{
  const cache = await caches.open(cacheName);
  try {{
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  }} catch (_) {{
    const cached = await cache.match(request);
    return cached || Response.error();
  }}
}}
"""

