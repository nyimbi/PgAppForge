def _resolve_model(model_name: str):
	"""
	Look up a SQLAlchemy mapped class by its ``__name__``.

	Searches the SQLAlchemy mapper registry; returns None if not found.
	"""
	try:
		from sqlalchemy.orm import class_mapper
		from sqlalchemy import inspect as sa_inspect
		from sqlalchemy.orm import DeclarativeBase
		# Walk the mapper registry
		from sqlalchemy.orm import registry as _registry_type
		import sqlalchemy.orm as _orm
		for mapper in _orm.mapperlib._mapper_registry:  # type: ignore[attr-defined]
			cls = mapper.class_
			if cls.__name__ == model_name:
				return cls
	except Exception:
		pass
	# Fallback: try iterating SQLAlchemy's global mapper registry
	try:
		import sqlalchemy
		from sqlalchemy.orm import DeclarativeMeta
		import gc
		for obj in gc.get_objects():
			if isinstance(obj, DeclarativeMeta) and getattr(obj, "__name__", "") == model_name:
				return obj
	except Exception:
		pass
	return None


def _coerce_pk(model_cls, pk_str: str):
	"""
	Convert a string PK to the column's Python type.

	Only handles integer PKs for now; returns the string as-is for others.
	"""
	try:
		from sqlalchemy import inspect as sa_inspect
		mapper = sa_inspect(model_cls)
		pk_cols = mapper.primary_key
		if pk_cols:
			col_type = pk_cols[0].type
			from sqlalchemy import Integer as _IntType
			if isinstance(col_type, _IntType):
				return int(pk_str)
	except Exception:
		pass
	return pk_str


def _record_to_dict(record) -> dict[str, Any]:
	"""Shallow-serialise a SQLAlchemy model instance to a plain dict."""
	try:
		from sqlalchemy import inspect as sa_inspect
		mapper = sa_inspect(type(record))
		return {col.key: getattr(record, col.key) for col in mapper.column_attrs}
	except Exception:
		return {}


def _detect_conflict(server_record, client_timestamp: str) -> bool:
	"""
	Return True if the server record was modified after ``client_timestamp``.

	Uses the ``changed_on`` or ``updated_at`` column when present.
	Falls back to False (no conflict) when the record is new or the
	timestamp cannot be parsed.
	"""
	if server_record is None:
		return False
	if not client_timestamp:
		return False

	server_ts = (
		getattr(server_record, "changed_on", None)
		or getattr(server_record, "updated_at", None)
	)
	if server_ts is None:
		return False

	try:
		from datetime import datetime, timezone
		client_dt = datetime.fromisoformat(client_timestamp.rstrip("Z")).replace(
			tzinfo=timezone.utc
		)
		if server_ts.tzinfo is None:
			server_ts = server_ts.replace(tzinfo=timezone.utc)
		return server_ts > client_dt
	except Exception:
		return False


def _apply_data(db_session, model_cls, server_record, pk_str: str, action: str, data: dict) -> None:
	"""
	Apply ``create``, ``update``, or ``delete`` to a model record.

	- ``create`` / ``update``: upsert field values from *data*
	- ``delete``: delete the record if it exists
	"""
	if action == "delete":
		if server_record is not None:
			db_session.delete(server_record)
		return

	if server_record is None:
		# create
		try:
			record = model_cls()
			for key, val in data.items():
				if hasattr(record, key):
					setattr(record, key, val)
			db_session.add(record)
		except Exception as exc:
			log.error("offline plugin: create failed for %s: %s", model_cls.__name__, exc)
			raise
	else:
		# update — only touch columns that exist on the model
		for key, val in data.items():
			if hasattr(server_record, key) and key not in ("id", "pk"):
				setattr(server_record, key, val)


