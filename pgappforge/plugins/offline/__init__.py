class OfflinePlugin(BasePlugin):
	"""
	Offline-first PWA plugin for PgAppForge.

	Features
	--------
	- Service Worker (``/sw.js``) with three caching strategies:
	  - static assets   → cache-first
	  - API GET routes  → stale-while-revalidate
	  - HTML pages      → network-first
	- ``/manifest.json`` for PWA installability
	- ``POST /offline/sync`` endpoint for batched operation replay
	- ``SyncConflict`` SQLAlchemy model for conflict persistence
	- ``OFFLINE_JS`` vanilla-JS helper (~100 lines) that queues mutations
	  in IndexedDB and auto-syncs when ``navigator.onLine`` fires

	Lifecycle
	---------
	1. ``initialize()``     — merge config defaults, validate strategy
	2. ``register_views()`` — register blueprint + admin view
	3. ``register_models()``— return [SyncConflict]
	4. ``_apply_operation()``— internal per-operation sync logic
	5. ``deactivate()``     — clean up via BasePlugin
	"""

	# ------------------------------------------------------------------
	# Metadata
	# ------------------------------------------------------------------

	@property
	def metadata(self) -> PluginMetadata:
		return PluginMetadata(
			name="offline",
			version="0.1.0",
			description=(
				"Offline-first PWA support: Service Worker, Web App Manifest, "
				"IndexedDB mutation queue, and server-side batch sync."
			),
			author="PgAppForge Contributors",
			tags=["offline", "pwa", "sync", "service-worker", "indexeddb"],
			priority=PluginPriority.NORMAL,
			permissions=[
				"can_view_OfflineSyncConflictView",
			],
			safe_mode_compatible=True,
			example_config={
				"PGAPPFORGE_OFFLINE_ENABLED": True,
				"PGAPPFORGE_OFFLINE_CACHE_TTL": 3600,
				"PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY": "server_wins",
			},
		)

	# ------------------------------------------------------------------
	# Lifecycle
	# ------------------------------------------------------------------

	def initialize(self) -> None:
		"""Merge config defaults and validate the conflict strategy."""
		merged = {**_DEFAULT_CONFIG, **self.config}

		# Also pull from Flask app config if available
		app_cfg = {}
		try:
			app = self.appbuilder.get_app
			for key in (
				"PGAPPFORGE_OFFLINE_ENABLED",
				"PGAPPFORGE_OFFLINE_CACHE_TTL",
				"PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY",
			):
				if key in app.config:
					app_cfg[key] = app.config[key]
		except Exception:
			pass

		# App config < plugin-level config (explicit caller wins)
		self.config = {**merged, **app_cfg, **{k: v for k, v in self.config.items() if k in merged}}
		# Re-merge so explicit constructor config takes precedence over app config
		self.config = {**merged, **app_cfg}
		# Then re-apply any constructor-supplied keys on top
		for k, v in merged.items():
			if k not in _DEFAULT_CONFIG or v != _DEFAULT_CONFIG[k]:
				self.config[k] = v

		self._validate_config()

		enabled = self.config.get("PGAPPFORGE_OFFLINE_ENABLED", False)
		log.info(
			"offline plugin: initialized (enabled=%s strategy=%s cache_ttl=%ss)",
			enabled,
			self.config.get("PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY"),
			self.config.get("PGAPPFORGE_OFFLINE_CACHE_TTL"),
		)

	def register_views(self) -> None:
		"""Register the Flask blueprint and the conflict admin view."""
		bp = _build_blueprint(self)
		self.register_blueprint(bp)

		self.add_view(
			OfflineSyncConflictView,
			"Sync Conflicts",
			icon="fa-exchange",
			category="Offline",
			category_icon="fa-wifi",
		)
		log.info("offline plugin: blueprint and views registered")

	def register_models(self) -> list:
		"""Return SQLAlchemy model classes for Alembic autogenerate."""
		if _MODELS_AVAILABLE:
			return [SyncConflict]
		log.warning("offline plugin: SQLAlchemy models unavailable — skipping")
		return []

	def get_config_schema(self) -> dict:
		"""JSON Schema for the admin plugin settings form."""
		return _CONFIG_SCHEMA

	# ------------------------------------------------------------------
	# Operation application (called by the sync endpoint)
	# ------------------------------------------------------------------

	def _apply_operation(self, op: dict[str, Any]) -> str:
		"""
		Apply a single offline operation to the database.

		Returns ``"applied"`` on success or ``"conflict"`` when the
		configured strategy routes the operation to the conflict table.

		Conflict resolution
		-------------------
		``server_wins``
			Discard client data; record the conflict row as resolved.
		``client_wins``
			Overwrite server record; resolve the conflict immediately.
		``manual``
			Write an unresolved SyncConflict row; return ``"conflict"``
			so the caller excludes it from the applied count.

		Args:
			op: Single operation dict with keys model, pk, action, data,
			    timestamp, device_id.

		Returns:
			``"applied"`` | ``"conflict"``
		"""
		model_name: str      = op.get("model", "")
		record_pk:  str      = str(op.get("pk", ""))
		action:     str      = op.get("action", "update")
		data:       dict     = op.get("data") or {}
		device_id:  str      = op.get("device_id", "unknown")
		timestamp:  str      = op.get("timestamp", "")

		# Resolve strategy: per-model override takes precedence
		default_strategy: str = self.config.get(
			"PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY", "server_wins"
		)
		strategy: str = (
			self.config.get("conflict_strategies", {}).get(model_name)
			or default_strategy
		)

		if not _MODELS_AVAILABLE:
			log.warning(
				"offline plugin: models unavailable — cannot apply op %s/%s",
				model_name, record_pk,
			)
			return "applied"

		try:
			db_session = self.appbuilder.get_session
		except Exception as exc:
			log.error("offline plugin: cannot get DB session: %s", exc)
			raise

		# Resolve the model class by name from SQLAlchemy's mapper registry
		model_cls = _resolve_model(model_name)

		if model_cls is None:
			log.warning("offline plugin: unknown model %r — skipping op", model_name)
			return "applied"

		# Fetch the current server record
		server_record = db_session.get(model_cls, _coerce_pk(model_cls, record_pk))
		server_data   = _record_to_dict(server_record) if server_record else None

		# Determine if this is a genuine conflict:
		# A conflict exists when the server record has been touched after
		# the client's last known timestamp for this record.
		is_conflict = _detect_conflict(server_record, timestamp)

		if is_conflict:
			conflict = SyncConflict(
				device_id=device_id,
				model_name=model_name,
				record_pk=record_pk,
				server_data=server_data,
				client_data=data,
				resolution_strategy=strategy,
			)

			if strategy == "server_wins":
				# Discard client change; mark conflict as resolved immediately
				conflict.resolved_at = datetime.now(timezone.utc)
				db_session.add(conflict)
				db_session.commit()
				log.debug(
					"offline plugin: server_wins conflict resolved for %s/%s",
					model_name, record_pk,
				)
				return "applied"

			elif strategy == "client_wins":
				# Apply client data, then mark conflict resolved
				_apply_data(db_session, model_cls, server_record, record_pk, action, data)
				conflict.resolved_at = datetime.now(timezone.utc)
				db_session.add(conflict)
				db_session.commit()
				log.debug(
					"offline plugin: client_wins applied for %s/%s",
					model_name, record_pk,
				)
				return "applied"

			else:  # "manual"
				db_session.add(conflict)
				db_session.commit()
				log.info(
					"offline plugin: manual conflict queued for %s/%s",
					model_name, record_pk,
				)
				return "conflict"

		# No conflict — apply the operation directly
		_apply_data(db_session, model_cls, server_record, record_pk, action, data)
		db_session.commit()
		log.debug("offline plugin: applied %s on %s/%s", action, model_name, record_pk)
		return "applied"

	# ------------------------------------------------------------------
	# Config validation
	# ------------------------------------------------------------------

	def _validate_config(self) -> None:
		strategy = self.config.get("PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY", "server_wins")
		valid = {"server_wins", "client_wins", "manual"}
		if strategy not in valid:
			raise ValueError(
				f"offline plugin: invalid PGAPPFORGE_OFFLINE_CONFLICT_STRATEGY {strategy!r}; "
				f"must be one of {sorted(valid)}"
			)
		for model_name, s in self.config.get("conflict_strategies", {}).items():
			if s not in valid:
				raise ValueError(
					f"offline plugin: invalid strategy {s!r} for model {model_name!r}; "
					f"must be one of {sorted(valid)}"
				)
		ttl = self.config.get("PGAPPFORGE_OFFLINE_CACHE_TTL", 3600)
		if not isinstance(ttl, int) or ttl < 0:
			raise ValueError(
				f"offline plugin: PGAPPFORGE_OFFLINE_CACHE_TTL must be a non-negative integer, got {ttl!r}"
			)


