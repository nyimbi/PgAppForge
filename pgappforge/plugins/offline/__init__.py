OFFLINE_JS = r"""
/* pgappforge-offline-client.js — auto-syncs queued mutations when reconnected */
(function (root) {
  'use strict';

  var DB_NAME    = 'pgaf_offline';
  var STORE_NAME = 'mutation_queue';
  var DB_VERSION = 1;
  var SYNC_URL   = '/offline/sync';

  /* ── IndexedDB bootstrap ── */
  var _db = null;

  function openDb() {
    return new Promise(function (resolve, reject) {
      if (_db) { resolve(_db); return; }
      var req = indexedDB.open(DB_NAME, DB_VERSION);
      req.onupgradeneeded = function (e) {
        var db    = e.target.result;
        var store = db.createObjectStore(STORE_NAME, { keyPath: 'id', autoIncrement: true });
        store.createIndex('by_timestamp', 'timestamp', { unique: false });
      };
      req.onsuccess = function (e) { _db = e.target.result; resolve(_db); };
      req.onerror   = function (e) { reject(e.target.error); };
    });
  }

  /* ── Queue a mutation for later sync ── */
  function queueMutation(model, pk, action, data, deviceId) {
    return openDb().then(function (db) {
      return new Promise(function (resolve, reject) {
        var tx    = db.transaction(STORE_NAME, 'readwrite');
        var store = tx.objectStore(STORE_NAME);
        var entry = {
          model:     model,
          pk:        pk,
          action:    action,          /* 'create' | 'update' | 'delete' */
          data:      data || {},
          timestamp: new Date().toISOString(),
          device_id: deviceId || _deviceId(),
        };
        var req = store.add(entry);
        req.onsuccess = function () { resolve(req.result); };
        req.onerror   = function () { reject(req.error); };
      });
    });
  }

  /* ── Read all queued mutations ── */
  function drainQueue() {
    return openDb().then(function (db) {
      return new Promise(function (resolve, reject) {
        var tx      = db.transaction(STORE_NAME, 'readonly');
        var store   = tx.objectStore(STORE_NAME);
        var req     = store.getAll();
        req.onsuccess = function () { resolve(req.result); };
        req.onerror   = function () { reject(req.error); };
      });
    });
  }

  /* ── Remove successfully synced mutations by id ── */
  function clearSynced(ids) {
    return openDb().then(function (db) {
      return new Promise(function (resolve, reject) {
        var tx    = db.transaction(STORE_NAME, 'readwrite');
        var store = tx.objectStore(STORE_NAME);
        var done  = 0;
        ids.forEach(function (id) {
          var req     = store.delete(id);
          req.onsuccess = function () { if (++done === ids.length) resolve(); };
          req.onerror   = function () { reject(req.error); };
        });
        if (ids.length === 0) resolve();
      });
    });
  }

  /* ── Sync queued mutations to the server ── */
  function sync() {
    if (!navigator.onLine) return Promise.resolve({ skipped: true });
    return drainQueue().then(function (ops) {
      if (!ops.length) return { applied: 0, conflicts: [], errors: [] };
      return fetch(SYNC_URL, {
        method:  'POST',
        headers: { 'Content-Type': 'application/json' },
        body:    JSON.stringify({ operations: ops }),
      })
      .then(function (r) { return r.json(); })
      .then(function (result) {
        /* Clear only the operations the server accepted */
        var acceptedIds = ops
          .slice(0, result.applied || 0)
          .map(function (op) { return op.id; })
          .filter(Boolean);
        return clearSynced(acceptedIds).then(function () { return result; });
      });
    });
  }

  /* ── Offline indicator badge ── */
  function _updateBadge(online) {
    var badge = document.getElementById('pgaf-offline-badge');
    if (!badge) {
      badge = document.createElement('span');
      badge.id = 'pgaf-offline-badge';
      badge.style.cssText = [
        'position:fixed', 'bottom:12px', 'right:12px', 'z-index:9999',
        'background:#c0392b', 'color:#fff', 'padding:4px 10px',
        'border-radius:4px', 'font-size:12px', 'font-weight:bold',
        'display:none', 'box-shadow:0 2px 6px rgba(0,0,0,.3)',
      ].join(';');
      badge.textContent = '⚡ Offline';
      document.body.appendChild(badge);
    }
    badge.style.display = online ? 'none' : 'block';
  }

  /* ── Stable per-browser device id ── */
  function _deviceId() {
    var key = 'pgaf_device_id';
    var id  = localStorage.getItem(key);
    if (!id) {
      id = 'dev-' + Math.random().toString(36).slice(2) + Date.now().toString(36);
      localStorage.setItem(key, id);
    }
    return id;
  }

  /* ── Service Worker registration ── */
  function registerSW(swUrl) {
    if (!('serviceWorker' in navigator)) return;
    navigator.serviceWorker.register(swUrl || '/sw.js')
      .then(function (reg) { console.debug('[pgaf-offline] SW registered', reg.scope); })
      .catch(function (err) { console.warn('[pgaf-offline] SW registration failed', err); });
  }

  /* ── Init: wire online/offline events ── */
  function init(options) {
    options = options || {};
    _updateBadge(navigator.onLine);
    window.addEventListener('online',  function () {
      _updateBadge(true);
      sync().then(function (r) {
        console.debug('[pgaf-offline] sync result', r);
      }).catch(function (e) {
        console.warn('[pgaf-offline] sync error', e);
      });
    });
    window.addEventListener('offline', function () { _updateBadge(false); });
    if (options.registerSW !== false) registerSW(options.swUrl);
  }

  /* ── Public API ── */
  var PgAfOffline = {
    init:          init,
    queueMutation: queueMutation,
    sync:          sync,
    deviceId:      _deviceId,
  };

  if (typeof module !== 'undefined' && module.exports) {
    module.exports = PgAfOffline;
  } else {
    root.PgAfOffline = PgAfOffline;
  }
}(typeof globalThis !== 'undefined' ? globalThis : this));
"""

