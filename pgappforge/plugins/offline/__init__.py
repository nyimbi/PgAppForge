def _build_blueprint(plugin: "OfflinePlugin") -> Blueprint:
	"""
	Build and return the Flask Blueprint for the offline plugin.

	Separated from the class so it can be unit-tested without a full
	AppBuilder instance.
	"""
	bp = Blueprint(
		"pgaf_offline",
		__name__,
		url_prefix="",          # sw.js must be served at the root scope
	)

	@bp.route("/sw.js")
	def service_worker() -> Response:
		"""Serve the generated Service Worker."""
		cfg = plugin.config
		body = (
			_SW_TEMPLATE
			.replace("{{ cache_ttl }}", str(cfg.get("PGAPPFORGE_OFFLINE_CACHE_TTL", 3600)))
			.replace("{{ cache_version }}", str(cfg.get("cache_version", "v1")))
		)
		resp = make_response(body, 200)
		resp.headers["Content-Type"] = "application/javascript"
		resp.headers["Service-Worker-Allowed"] = "/"
		resp.headers["Cache-Control"] = "no-cache, no-store"
		return resp

	@bp.route("/manifest.json")
	def manifest() -> Response:
		"""Serve the PWA Web App Manifest."""
		cfg = plugin.config
		body = (
			_MANIFEST_TEMPLATE
			.replace("{{ app_name }}",        cfg.get("app_name", "PgAppForge"))
			.replace("{{ short_name }}",       cfg.get("app_short_name", "PgAF"))
			.replace("{{ app_description }}",  cfg.get("app_description", ""))
			.replace("{{ icon_192 }}",         cfg.get("icon_192", "/static/appbuilder/img/icon-192.png"))
			.replace("{{ icon_512 }}",         cfg.get("icon_512", "/static/appbuilder/img/icon-512.png"))
		)
		resp = make_response(body, 200)
		resp.headers["Content-Type"] = "application/manifest+json"
		resp.headers["Cache-Control"] = "no-cache"
		return resp

	@bp.route("/offline/sync", methods=["POST"])
	def sync_endpoint() -> Response:
		"""
		Batch-apply client operations queued while offline.

		Request body (JSON)::

		    {
		      "operations": [
		        {
		          "model":     "Employee",
		          "pk":        "42",
		          "action":    "update",     // create | update | delete
		          "data":      {...},
		          "timestamp": "2026-05-30T12:00:00Z",
		          "device_id": "dev-abc123"
		        }
		      ]
		    }

		Response::

		    {
		      "applied":   N,
		      "conflicts": [{...}],
		      "errors":    [{...}]
		    }
		"""
		if not plugin.config.get("PGAPPFORGE_OFFLINE_ENABLED", False):
			return jsonify({"error": "offline sync is disabled"}), 503

		payload = request.get_json(silent=True) or {}
		operations: list[dict[str, Any]] = payload.get("operations", [])

		applied:   int             = 0
		conflicts: list[dict[str, Any]] = []
		errors:    list[dict[str, Any]] = []

		for op in operations:
			try:
				result = plugin._apply_operation(op)
				if result == "applied":
					applied += 1
				elif result == "conflict":
					conflicts.append({
						"model":  op.get("model"),
						"pk":     op.get("pk"),
						"action": op.get("action"),
					})
			except Exception as exc:
				log.error("offline plugin: sync error for op %s: %s", op, exc)
				errors.append({
					"model":   op.get("model"),
					"pk":      op.get("pk"),
					"action":  op.get("action"),
					"message": str(exc),
				})

		log.info(
			"offline plugin: sync — applied=%d conflicts=%d errors=%d",
			applied, len(conflicts), len(errors),
		)
		return jsonify({"applied": applied, "conflicts": conflicts, "errors": errors})

	return bp

